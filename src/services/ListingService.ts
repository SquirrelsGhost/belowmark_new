function snapshotPath(market: MarketCode): string {
  return market === "TR"
    ? join(process.cwd(), "data", "snapshots", "tr.json")
    : join(process.cwd(), "data", "snapshots", "de.json");
}

/** Snapshot files written by scripts/build-snapshots.mjs — literal paths so the bundler can trace them. */
function readSnapshot(market: MarketCode): Promise<string> {
  return market === "TR"
    ? readFile(join(process.cwd(), "data", "snapshots", "tr.json"), "utf8")
    : readFile(join(process.cwd(), "data", "snapshots", "de.json"), "utf8");
}

/** Per-country EU shard files generated by scripts/build-country-shards.mjs — literal paths for bundler tracing. */
function readCountryShardFile(country: Exclude<ListingCountry, "TR">): Promise<string> {
  const dir = join(process.cwd(), "data", "snapshots", "countries");
  switch (country) {
    case "AT":
      return readFile(join(dir, "at.json"), "utf8");
    case "CH":
      return readFile(join(dir, "ch.json"), "utf8");
    case "IT":
      return readFile(join(dir, "it.json"), "utf8");
    case "ES":
      return readFile(join(dir, "es.json"), "utf8");
    case "FR":
      return readFile(join(dir, "fr.json"), "utf8");
    case "GB":
      return readFile(join(dir, "gb.json"), "utf8");
    case "NL":
      return readFile(join(dir, "nl.json"), "utf8");
    case "PL":
      return readFile(join(dir, "pl.json"), "utf8");
    case "CZ":
      return readFile(join(dir, "cz.json"), "utf8");
    case "SE":
      return readFile(join(dir, "se.json"), "utf8");
    default:
      return readFile(join(dir, "de.json"), "utf8");
  }
}

