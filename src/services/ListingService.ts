/** Lower case, no accents, Turkish dotless i folded — "cesme" finds "Çeşme". */
export function normalizeText(value: string): string {
  return value
    .replace(/İ/g, "i")
    .replace(/ı/g, "i")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/ß/g, "ss");
}

function buildHaystack(listing: Listing): string {
  const cMap: Record<DachCountry, string> = {
    DE: "deutschland germany zvg",
    AT: "österreich austria ediktsdatei",
    CH: "schweiz switzerland shab",
    IT: "italien italy italia aste giudiziarie",
    ES: "spanien spain espana boe subastas",
    FR: "frankreich france licitor notaires avoventes immo-interactif",
    GB: "england uk united kingdom grossbritannien",
    NL: "niederlande netherlands nederland executieveiling vastgoedveiling",
    PL: "polen poland polska licytacje komornicze komornik",
    CZ: "tschechien czechia cesko drazby nemovitosti portaldrazeb exekuce",
    SE: "schweden sweden sverige kronofogden exekutiv auktion fastighet bostadsratt",
  };
  const countryTag = listing.market === "DE" ? cMap[getListingDachCountry(listing)] : null;
  const parts = [
    listing.title,
    listing.place,
    listing.postcode,
    listing.street,
    listing.authority,
    listing.fileNo,
    listing.region,
    listing.segmentLabel,
    listing.sourcePortal,
    listing.grundbuch,
    listing.rooms,
    listing.proceedingKind,
    listing.description,
    countryTag,
    listing.tr?.adType,
    listing.tr?.source,
    listing.tr?.mahalle,
    listing.tr?.nitelik,
    listing.tr?.zoning,
    listing.tr?.rooms,
    listing.tr?.floor,
    listing.tr?.excerpt,
    listing.tr?.ada && listing.tr?.parsel ? `${listing.tr.ada}/${listing.tr.parsel}` : null,
  ];
  return normalizeText(parts.filter(Boolean).join(" "));
}

export function isOpportunityListing(listing: Listing): boolean {
  if (listing.market === "TR") {
    return (listing.tr?.discountPct ?? 0) >= 25 || Boolean(listing.tr?.adType && listing.tr.adType !== "İCRA");
  }
  return Boolean(listing.limitsWaived);
}

export function hasListingDocs(listing: Listing): boolean {
  if (listing.market === "TR") {
    return Boolean(listing.tr?.marketMedianPerM2 || (listing.tr?.ada && listing.tr?.parsel));
  }
  return Boolean(listing.documentUrl || listing.exposeUrl || listing.biddingNotesUrl);
}

function opportunityScore(listing: Listing): number {
  if (listing.market === "TR") {
    const disc = listing.tr?.discountPct ?? -500;
    const bonus = listing.tr?.adType && listing.tr.adType !== "İCRA" ? 20 : 0;
    return disc + bonus;
  }
  return (
    (listing.limitsWaived ? 1000 : 0) +
    (listing.exposeUrl ? 200 : 0) +
    (listing.documentUrl ? 100 : 0) +
    (listing.appraisedValue ? 10 : 0)
  );
}

